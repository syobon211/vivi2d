import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const failures = [];
const checklistPath = path.join(
  root,
  "docs/developer/quality/public-release-checklist.md",
);
const workflowsDir = path.join(root, ".github/workflows");

const UPLOAD_ACTION = "actions/upload-artifact@043fb46d1a93c77aae656e7c1c64a875d1fc6a0a";
const ARTIFACT_JOBS = {
  "github-release-alpha.yml": {
    "validate-and-package-github-release": {
      environment: "desktop-installer-alpha",
      artifacts: { "github-release-alpha-assets": ["tmp/github-release-assets/"] },
    },
  },
  "windows-installer-alpha.yml": {
    "linux-validation": {
      environment: "desktop-installer-alpha",
      artifacts: {
        "windows-installer-alpha-baseline": ["tmp/windows-installer-baseline/"],
      },
    },
    "windows-packaging": {
      environment: "desktop-installer-alpha",
      artifacts: {
        "windows-installer-alpha-assets": ["tmp/windows-installer-alpha-assets/"],
        "windows-installer-alpha-baseline-windows": ["transcripts/"],
      },
    },
  },
  "publish-web-alpha.yml": {
    "validate-and-pack-web-alpha": {
      environment: "npm-alpha",
      artifacts: {
        "web-npm-alpha-release-record": [
          "web-pack-result.json",
          "web-npm-alpha-release-record.json",
          "*.tgz",
          "transcripts/",
          "dist/sbom/",
        ],
      },
    },
  },
};

function fail(message) {
  failures.push(message);
}

function readText(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), "utf8");
}

function checkChecklist() {
  if (!fs.existsSync(checklistPath)) {
    fail("docs/developer/quality/public-release-checklist.md is missing.");
    return;
  }
  const text = readText("docs/developer/quality/public-release-checklist.md");
  for (const pattern of [
    /Full git history scanned/i,
    /Actions logs, workflow summaries, and retained artifacts reviewed/i,
    /Hosted-surface findings remediated/i,
    /workflow artifacts do not include private paths/i,
    /provider payloads/i,
    /synthetic public fixtures/i,
    /gitleaks/i,
  ]) {
    if (!pattern.test(text)) {
      fail(`public release checklist is missing hosted-surface item ${pattern}.`);
    }
  }
}

function checkWorkflowArtifacts() {
  if (!fs.existsSync(workflowsDir)) {
    fail(".github/workflows is missing.");
    return;
  }
  for (const entry of fs.readdirSync(workflowsDir, { withFileTypes: true })) {
    if (!entry.isFile() || !/\.ya?ml$/i.test(entry.name)) continue;
    const relativePath = `.github/workflows/${entry.name}`;
    const lines = readText(relativePath)
      .split(/\r?\n/)
      .filter((line) => line.trim() && !/^\s*#/.test(line));
    const references = lines.filter((line) => /actions\/upload-artifact/i.test(line));
    const policy = ARTIFACT_JOBS[entry.name];
    if (!policy) {
      if (references.length)
        fail(
          `${relativePath}: automatic CI artifact upload is forbidden outside reviewed release producers.`,
        );
      continue;
    }
    // A deliberately narrow template check, not a general YAML parser or a
    // claim that arbitrary generated bytes are safe. Syntax changes need review.
    if (lines.filter((line) => line === "jobs:").length !== 1) {
      fail(`${relativePath}: release workflow must have one explicit jobs block.`);
      continue;
    }
    const jobs = new Map();
    let current;
    for (const line of lines.slice(lines.indexOf("jobs:") + 1)) {
      const match = /^ {2}([a-z0-9-]+):$/.exec(line);
      if (match) {
        if (jobs.has(match[1])) fail(`${relativePath}: duplicate release job.`);
        current = [];
        jobs.set(match[1], current);
      } else if (current) {
        current.push(line);
      }
    }
    let checkedUploads = 0;
    for (const [jobName, requirements] of Object.entries(policy)) {
      const job = jobs.get(jobName);
      if (!job) {
        fail(`${relativePath}: missing approved artifact producer ${jobName}.`);
        continue;
      }
      checkedUploads += checkProducer(relativePath, jobName, job, requirements);
    }
    if (checkedUploads !== references.length) {
      fail(`${relativePath}: artifact upload is outside the approved job/step template.`);
    }
  }
}

function checkProducer(workflowPath, jobName, lines, policy) {
  const label = `${workflowPath}:${jobName}`;
  const environment = lines.filter((line) => /^ {4}environment:/.test(line));
  if (
    environment.length !== 1 ||
    environment[0] !== `    environment: ${policy.environment}`
  ) {
    fail(`${label}: artifact producer must use its literal protected environment.`);
  }
  if (lines.some((line) => /^ {4}(?:if|continue-on-error):/.test(line))) {
    fail(`${label}: producer must not override normal success/failure handling.`);
  }
  if (lines.some((line) => /^ {4,8}(?:<<:|[^:]+:\s*[*&{])|^ {6}-\s*[*&{]/.test(line))) {
    fail(`${label}: producer must use explicit block syntax without aliases or merges.`);
  }
  if (lines.filter((line) => line === "    steps:").length !== 1) {
    fail(`${label}: producer must have one explicit steps block.`);
  }
  const steps = [];
  for (const line of lines.slice(lines.indexOf("    steps:") + 1)) {
    if (/^ {6}- /.test(line)) steps.push([line]);
    else if (steps.length) steps.at(-1).push(line);
  }
  if (
    steps.some((step) =>
      step.some((line) =>
        /^ {6}(?:- | {2})["']?(?:if|continue-on-error)["']?:/.test(line),
      ),
    )
  ) {
    fail(
      `${label}: producer steps must not skip or continue after failed generation or validation.`,
    );
  }
  const liveCommand = `node scripts/check-environment-protection.mjs --live --environment ${policy.environment}`;
  const expectedLiveStep = [
    "      - name: Verify live release environment before build",
    "        env:",
    "          GH_TOKEN: $" + "{{ github.token }}",
    `        run: ${liveCommand}`,
  ].join("\n");
  const liveSteps = steps.flatMap((step, index) =>
    step.join("\n") === expectedLiveStep ? [index] : [],
  );
  if (liveSteps.length !== 1)
    fail(`${label}: requires one unconditional, authenticated live environment check.`);
  const liveIndex = liveSteps[0] ?? -1;
  for (const step of steps.slice(0, Math.max(0, liveIndex))) {
    if (
      step.some((line) => /^ {6,8}(?:- )?run:/.test(line)) &&
      !/^ {6}- name: Verify (?:installer )?release tag\b/.test(step[0])
    ) {
      fail(
        `${label}: live environment check must precede build and repository commands.`,
      );
    }
  }
  const names = [];
  let uploads = 0;
  for (const [index, step] of steps.entries()) {
    if (!step.some((line) => /actions\/upload-artifact/i.test(line))) continue;
    uploads += 1;
    if (liveIndex < 0 || index <= liveIndex)
      fail(`${label}: live check must succeed before artifact upload.`);
    const name = checkUpload(label, step, policy.artifacts);
    if (name) names.push(name);
  }
  if (
    JSON.stringify(names.sort()) !== JSON.stringify(Object.keys(policy.artifacts).sort())
  ) {
    fail(
      `${label}: artifact names must match the exact approved set without duplicates.`,
    );
  }
  return uploads;
}

function checkUpload(label, step, artifacts) {
  if (
    step[0]?.replace(/ +#.*$/, "") !== `      - uses: ${UPLOAD_ACTION}` ||
    step[1] !== "        with:"
  ) {
    fail(
      `${label}: artifact upload must use the pinned explicit step with default success handling.`,
    );
  }
  const inputs = new Map();
  let paths = [];
  for (let index = 2; index < step.length; index += 1) {
    const match = /^ {10}(name|path|retention-days|if-no-files-found): (.+)$/.exec(
      step[index],
    );
    if (!match || inputs.has(match[1])) {
      fail(`${label}: artifact upload has unsupported or duplicate input/step syntax.`);
      continue;
    }
    inputs.set(match[1], match[2]);
    if (match[1] !== "path") continue;
    if (match[2] !== "|") paths = [match[2]];
    else {
      while (index + 1 < step.length && /^ {12}\S/.test(step[index + 1])) {
        paths.push(step[++index].slice(12));
      }
    }
  }
  const name = inputs.get("name");
  const expectedPaths = Object.hasOwn(artifacts, name ?? "") ? artifacts[name] : null;
  if (!expectedPaths || JSON.stringify(paths) !== JSON.stringify(expectedPaths)) {
    fail(`${label}: artifact upload name/path set is not explicitly approved.`);
  }
  const days = inputs.get("retention-days");
  if (!/^\d+$/.test(days ?? "") || Number(days) < 1 || Number(days) > 14) {
    fail(`${label}: artifact upload retention-days must be 1..14.`);
  }
  if (inputs.get("if-no-files-found") !== "error") {
    fail(`${label}: artifact upload must fail on missing files.`);
  }
  return name;
}

checkChecklist();
checkWorkflowArtifacts();

if (failures.length > 0) {
  console.error("[hosted-release-surfaces] failed:");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log("[hosted-release-surfaces] passed");
