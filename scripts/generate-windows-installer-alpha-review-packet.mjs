function renderWorkflowContract() {
  const workflow = fs.readFileSync(
    resolveRepoPath(".github/workflows/windows-installer-alpha.yml"),
    "utf8",
  );
  const linuxJob = requireSection(
    workflow,
    "  linux-validation:",
    "  windows-packaging:",
  );
  const windowsJob = requireSection(
    workflow,
    "  windows-packaging:",
    "  verify-windows-installer-assets:",
  );
  const verifyJob = requireSection(
    workflow,
    "  verify-windows-installer-assets:",
    "  create-windows-installer-release:",
  );
  const releaseJob = requireSection(
    workflow,
    "  create-windows-installer-release:",
    null,
  );
  const jobs = {
    linuxValidation: summarizeJob(linuxJob),
    windowsPackaging: summarizeJob(windowsJob),
    verifyWindowsInstallerAssets: summarizeJob(verifyJob),
    createWindowsInstallerRelease: summarizeJob(releaseJob),
  };
  return ["```json", JSON.stringify(jobs, null, 2), "```"].join("\n");
}

function summarizeJob(jobSection) {
  const steps = parseWorkflowSteps(jobSection);
  return {
    envKeys: extractTopLevelEnvKeys(jobSection),
    reusableActions: steps.filter((step) => step.uses).map((step) => step.uses),
    runSteps: steps.filter((step) => step.run).map((step) => step.run),
    tokenMentions: steps
      .filter((step) => /\b(?:GH_TOKEN|GITHUB_TOKEN|GITHUB_TOKEN:)\b/.test(step.raw))
      .map((step) => step.name || step.uses || `step-${step.index}`),
  };
}

