import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, "..");
if (
  process.argv
    .slice(2)
    .some((arg) => !["--check", "--png-v1", "--evaluation-v1"].includes(arg))
) {
  throw new Error("Only --check and the fixed PNG or Evaluation modes are supported");
}
const checkOnly = process.argv.includes("--check");
const pngMode = process.argv.includes("--png-v1");
const evaluationMode = process.argv.includes("--evaluation-v1");
if (pngMode && evaluationMode) throw new Error("Select exactly one WASM profile");
const modeArgument = evaluationMode ? " --evaluation-v1" : pngMode ? " --png-v1" : "";
const wasmPath = path.join(
  root,
  evaluationMode
    ? "packages/runtime-native/target/evaluation-v1/wasm32-unknown-unknown/release/vivi_runtime_native_wasm.wasm"
    : pngMode
      ? "packages/runtime-native/target/png-v1/wasm32-unknown-unknown/release/vivi_runtime_native_wasm.wasm"
      : "packages/runtime-native/target/wasm32-unknown-unknown/release/vivi_runtime_native_wasm.wasm",
);
const outputPath = path.join(
  root,
  evaluationMode
    ? "packages/runtime-wasm/src/native-evaluation-wasm-bytes.ts"
    : pngMode
      ? "packages/runtime-wasm/src/native-png-wasm-bytes.ts"
      : "packages/runtime-wasm/src/native-wasm-bytes.ts",
);
const exportName = evaluationMode
  ? "VIVI_RUNTIME_NATIVE_EVALUATION_WASM_BASE64"
  : pngMode
    ? "VIVI_RUNTIME_NATIVE_PNG_WASM_BASE64"
    : "VIVI_RUNTIME_NATIVE_WASM_BASE64";

const wasmBase64 = readFileSync(wasmPath).toString("base64");
const lines = wasmBase64.match(/.{1,100}/g) ?? [""];
const source = `// Generated by scripts/generate-runtime-native-wasm-module.mjs${modeArgument}.\n// Do not edit by hand.\n\nexport const ${exportName} = [\n${lines
  .map((line) => `  "${line}",`)
  .join("\n")}\n].join("");\n`;

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (current !== source) {
    throw new Error(
      `${path.relative(root, outputPath)} is stale; run node scripts/generate-runtime-native-wasm-module.mjs${modeArgument}`,
    );
  }
  console.log("[runtime-native-wasm] generated TypeScript bytes are current");
  process.exit(0);
}

writeFileSync(outputPath, source);
console.log(`[runtime-native-wasm] wrote ${path.relative(root, outputPath)}`);
