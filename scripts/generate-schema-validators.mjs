function loadApprovedSchema(identity) {
  const absolutePath = path.join(root, identity.relativePath);
  const bytes = fs.readFileSync(absolutePath);
  const actualSha256 = createHash("sha256").update(bytes).digest("hex");
  if (actualSha256 !== identity.sha256) {
    throw new Error(
      `${identity.relativePath} SHA-256 mismatch: expected ${identity.sha256}, got ${actualSha256}`,
    );
  }

  const schema = JSON.parse(bytes.toString("utf8"));
  if (schema.$id !== identity.id) {
    throw new Error(
      `${identity.relativePath} schema ID mismatch: expected ${identity.id}, got ${String(schema.$id)}`,
    );
  }
  if (schema["x-vivi-status"] !== APPROVED_STATUS) {
    throw new Error(
      `${identity.relativePath} schema status mismatch: expected ${APPROVED_STATUS}, got ${String(schema["x-vivi-status"])}`,
    );
  }
  return { identity, schema };
}

function createModuleSource(output, standalone) {
  const withoutStrictDirective = standalone.replace(/^"use strict";\s*/u, "");
  const { sourceWithHelpers, helperCounts } =
    inlineRuntimeHelpers(withoutStrictDirective);
  for (const helperName of ["equal", "ucs2length"]) {
    const expected = output.expectedHelpers[helperName];
    const actual = helperCounts[helperName];
    if (actual !== expected) {
      throw new Error(
        `${output.modulePath} Ajv ${helperName} helper count drifted: expected ${expected}, got ${actual}`,
      );
    }
  }

  const identitySource = Object.entries(output.identityExports)
    .map(([exportName, identity]) => {
      const value = {
        id: identity.id,
        status: APPROVED_STATUS,
        sha256: identity.sha256,
      };
      return `export const ${exportName} = Object.freeze(${JSON.stringify(value)});`;
    })
    .join("\n");
  const source = [
    "// Generated by scripts/generate-schema-validators.mjs. Do not edit.",
    "// The schema hashes below are verified before Ajv standalone generation.",
    identitySource,
    sourceWithHelpers.trimEnd(),
    "",
  ].join("\n");
  assertPortableRuntimeSource(output.modulePath, source);
  return source;
}

function inlineRuntimeHelpers(source) {
  const helperCounts = { equal: 0, ucs2length: 0 };
  const equalPattern =
    /const (func\d+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/gu;
  const ucs2LengthPattern =
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/gu;

  let sourceWithHelpers = source.replace(equalPattern, (_match, binding) => {
    helperCounts.equal += 1;
    return `const ${binding} = function equal(left, right) {
  if (left === right) return true;
  if (left && right && typeof left === "object" && typeof right === "object") {
    if (left.constructor !== right.constructor) return false;
    let length;
    let index;
    let keys;
    if (Array.isArray(left)) {
      length = left.length;
      if (length !== right.length) return false;
      for (index = length; index-- !== 0; ) {
        if (!equal(left[index], right[index])) return false;
      }
      return true;
    }
    if (left.constructor === RegExp) {
      return left.source === right.source && left.flags === right.flags;
    }
    if (left.valueOf !== Object.prototype.valueOf) {
      return left.valueOf() === right.valueOf();
    }
    if (left.toString !== Object.prototype.toString) {
      return left.toString() === right.toString();
    }
    keys = Object.keys(left);
    length = keys.length;
    if (length !== Object.keys(right).length) return false;
    for (index = length; index-- !== 0; ) {
      if (!Object.prototype.hasOwnProperty.call(right, keys[index])) return false;
    }
    for (index = length; index-- !== 0; ) {
      const key = keys[index];
      if (!equal(left[key], right[key])) return false;
    }
    return true;
  }
  return left !== left && right !== right;
};`;
  });

  sourceWithHelpers = sourceWithHelpers.replace(ucs2LengthPattern, (_match, binding) => {
    helperCounts.ucs2length += 1;
    return `const ${binding} = function ucs2length(value) {
  const length = value.length;
  let codePointLength = 0;
  let position = 0;
  let codeUnit;
  while (position < length) {
    codePointLength += 1;
    codeUnit = value.charCodeAt(position++);
    if (codeUnit >= 0xd800 && codeUnit <= 0xdbff && position < length) {
      codeUnit = value.charCodeAt(position);
      if ((codeUnit & 0xfc00) === 0xdc00) position += 1;
    }
  }
  return codePointLength;
};`;
  });
  return { helperCounts, sourceWithHelpers };
}

function assertPortableRuntimeSource(relativePath, source) {
  const forbidden = [
    ["CommonJS require", /\brequire\s*\(/u],
    ["eval", /\beval\s*\(/u],
    ["Function constructor", /\b(?:new\s+)?Function\s*\(/u],
    ["runtime Ajv import", /\b(?:from|import\s*\()\s*["']ajv(?:\/|["'])/u],
  ];
  for (const [label, pattern] of forbidden) {
    if (pattern.test(source)) {
      throw new Error(`${relativePath} contains forbidden ${label}`);
    }
  }
}

function createDeclarationSource(output) {
  const identityDeclarations = Object.keys(output.identityExports)
    .map((exportName) => `export const ${exportName}: Readonly<ApprovedSchemaIdentity>;`)
    .join("\n");
  const validatorDeclarations = Object.keys(output.validatorExports)
    .map((exportName) => `export const ${exportName}: StandaloneSchemaValidator;`)
    .join("\n");
  return `${declarationHeader}${identityDeclarations}\n${validatorDeclarations}\n`;
}

function writeOrCheck(relativePath, expectedSource) {
  const absolutePath = path.join(root, relativePath);
  if (checkOnly) {
    if (!fs.existsSync(absolutePath)) {
      throw new Error(`${relativePath} is missing; run the generator`);
    }
    const actualSource = fs.readFileSync(absolutePath, "utf8");
    if (actualSource !== expectedSource) {
      throw new Error(`${relativePath} is stale; run the generator`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  fs.writeFileSync(absolutePath, expectedSource, "utf8");
}
